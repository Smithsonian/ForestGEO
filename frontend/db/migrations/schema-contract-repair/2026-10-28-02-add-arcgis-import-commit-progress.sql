-- An ArcGIS commit is now a sequence of separately committed transactions tracked on
-- its import session (claim, clearing an earlier attempt's leftovers, staging windows,
-- the census replacement, finalization) instead of one all-or-nothing transaction.
-- Four columns carry that progress:
--   committed_upload_mode            the mode the first claim committed to; later claims must match it
--   commit_attempt_id                fencing token: the one attempt allowed to run units
--   census_replacement_completed_at  per-import census-replacement marker, set by the last replacement unit
--   staging_next_row_index           staging cursor of the current attempt
--
-- Existing rows are correct with the defaults. A 'preflight' row has not started. A
-- 'committed' row never reads these columns: replaying a session committed before this
-- migration reads committed_upload_mode NULL, which the claim treats as "recorded before
-- modes were stored" and answers by the batch rule that applied then.
--
-- Each column has its own guarded PREPARE: a no-op when the table is absent or the
-- column already exists, so the file is idempotent and completes a partially applied
-- state. ADD COLUMN at the end of this small table runs in place on MySQL 8.0.
--
